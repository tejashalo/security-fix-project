'use strict';
const { posix } = require('../lib/util');

module.exports = {
  id: 'database',
  title: 'Securing the database (RLS, Firebase rules, exposure)',
  async run(ctx) {
    const { p, det } = ctx;
    let seen = det.frameworks.has('Supabase') || det.frameworks.has('Firebase') || det.frameworks.has('MongoDB') || det.frameworks.has('SQL database') || det.frameworks.has('Prisma');

    // ---------- Supabase RLS ----------
    const sqlFiles = p.files.filter((f) => /\.sql$/.test(f.path) && !f.skipped && f.size < 2e6).map((f) => f.path);
    const created = new Map(); // table -> file
    const rlsOn = new Set();
    for (const f of sqlFiles) {
      const c = p.read(f) || '';
      let m;
      const ct = /create\s+table\s+(?:if\s+not\s+exists\s+)?((?:"?public"?\.)?"?[\w]+"?)/gi;
      while ((m = ct.exec(c))) { const t = m[1].replace(/"/g, '').replace(/^public\./i, ''); if (!created.has(t)) created.set(t, { file: f, index: m.index }); }
      const rl = /alter\s+table\s+(?:only\s+)?((?:"?public"?\.)?"?[\w]+"?)\s+enable\s+row\s+level\s+security/gi;
      while ((m = rl.exec(c))) rlsOn.add(m[1].replace(/"/g, '').replace(/^public\./i, ''));
      const openPolicy = /create\s+policy[\s\S]{0,300}?using\s*\(\s*true\s*\)/gi;
      while ((m = openPolicy.exec(c))) {
        seen = true;
        const stmt = c.slice(m.index, m.index + 400);
        const write = /for\s+(insert|update|delete|all)/i.test(stmt);
        ctx.at(f, m.index, { category: 'database', severity: write ? 'critical' : 'medium', title: `RLS policy allows everyone (USING (true))${write ? ' to write' : ''}`, why: write ? 'Anyone with your public anon key can modify or delete rows.' : 'Every row is readable by anyone with your public anon key — fine only for truly public data.', fix: 'Restrict with the owner column, e.g. USING (auth.uid() = user_id).' });
      }
    }
    const isSupabase = det.frameworks.has('Supabase');
    if (isSupabase && created.size) {
      const missing = [...created.keys()].filter((t) => !rlsOn.has(t));
      if (missing.length) {
        seen = true;
        const first = created.get(missing[0]);
        const fd = ctx.at(first.file, first.index, {
          category: 'database', severity: 'critical', title: `Row Level Security is OFF for ${missing.length} table(s): ${missing.slice(0, 5).join(', ')}${missing.length > 5 ? '…' : ''}`,
          why: 'Supabase tables without RLS can be read, changed and deleted by anyone using the anon key that ships in your front-end. This is the #1 way vibe-coded apps leak user data.',
          fix: 'Enable RLS on every table and add policies (e.g. users can only read/write rows where user_id = auth.uid()).',
        });
        const dir = p.dirs.includes('supabase/migrations') ? 'supabase/migrations' : posix.dirname(first.file);
        const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
        const file = `${dir === '.' ? '' : dir + '/'}${stamp}_vibeguard_enable_rls.sql`;
        const sql = `-- Generated by VibeGuard. Review, then apply with \`supabase db push\` or the SQL editor.\n-- Enabling RLS with no policies DENIES all access through the anon/authenticated keys,\n-- so add a policy for each table your app needs (examples below).\n\n`
          + missing.map((t) => `alter table public.${t} enable row level security;\n-- Example owner-only policies (adjust the column name):\n-- create policy "${t}: owners read"   on public.${t} for select using (auth.uid() = user_id);\n-- create policy "${t}: owners write"  on public.${t} for insert with check (auth.uid() = user_id);\n-- create policy "${t}: owners update" on public.${t} for update using (auth.uid() = user_id);\n-- create policy "${t}: owners delete" on public.${t} for delete using (auth.uid() = user_id);\n`).join('\n');
        ctx.createFile(file, sql, 'Migration that enables Row Level Security on every table, with example policies.');
        ctx.markFixed(fd, { before: '(RLS disabled)', after: `${file}`, summary: `Generated ${file}. It is NOT applied automatically — review the policies and run it.` });
        ctx.note(`Apply the generated Supabase migration (${file}) after adding policies for each table — RLS with no policy blocks all client access.`);
      }
    } else if (isSupabase) {
      seen = true;
      ctx.add({ category: 'database', severity: 'high', file: null, title: 'Verify Row Level Security on every Supabase table', why: 'No SQL migrations were found, so VibeGuard cannot see your RLS settings. Tables without RLS are public to anyone with the anon key.', fix: 'Supabase dashboard → Authentication → Policies: make sure every table shows "RLS enabled" and has owner-based policies. Run the Security Advisor in the dashboard.' });
    }

    // ---------- Firebase rules ----------
    for (const f of p.files.filter((x) => /(^|\/)(firestore|storage)\.rules$|(^|\/)database\.rules\.json$/.test(x.path)).map((x) => x.path)) {
      seen = true;
      const c = p.read(f) || '';
      const edits = [];
      let m;
      const open = /allow\s+((?:read|write|get|list|create|update|delete)(?:\s*,\s*(?:read|write|get|list|create|update|delete))*)\s*(?::\s*if\s+(true|request\.time\s*<\s*timestamp\.date\([^)]*\)))?\s*;/g;
      while ((m = open.exec(c))) {
        if (m[2] === undefined && !/allow\s+[\w\s,]+;/.test(m[0])) continue;
        const fd = ctx.at(f, m.index, { category: 'database', severity: 'critical', title: m[2] && m[2].startsWith('request.time') ? 'Firebase rules still in "test mode"' : 'Firebase rules allow everyone', why: 'Anyone on the internet can read and overwrite your database/storage using the config in your front-end.', fix: 'Require authentication and ownership, e.g. `allow read, write: if request.auth != null && request.auth.uid == resource.data.userId;`' });
        edits.push({ index: m.index, old: m[0], new: `allow ${m[1]}: if request.auth != null; // VibeGuard: tighten to owner checks, e.g. request.auth.uid == resource.data.userId`, finding: fd, summary: 'Now requires a signed-in user. Tighten further to per-user ownership.' });
      }
      if (/\.json$/.test(f)) {
        const rr = /"\.(read|write)"\s*:\s*true/g;
        while ((m = rr.exec(c))) {
          const fd = ctx.at(f, m.index, { category: 'database', severity: 'critical', title: `Realtime Database ".${m[1]}": true`, why: 'Your whole database is public.', fix: 'Use "auth != null" (and per-user paths like "$uid === auth.uid").' });
          edits.push({ index: m.index, old: m[0], new: `".${m[1]}": "auth != null"`, finding: fd, summary: 'Now requires a signed-in user.' });
        }
      }
      ctx.applyEdits(f, edits);
    }
    if (det.frameworks.has('Firebase') && !p.files.some((x) => /firestore\.rules|database\.rules\.json|storage\.rules/.test(x.path))) {
      ctx.add({ category: 'database', severity: 'high', file: null, title: 'Firebase Security Rules are not in the project', why: 'Your Firebase config is public by design; Security Rules are the only thing protecting the data. VibeGuard cannot see them.', fix: 'In the Firebase console → Firestore/Storage → Rules, make sure nothing says `allow read, write: if true` or a test-mode date. Keep rules in the repo (firebase init firestore).' });
    }

    // ---------- docker-compose database ports & default passwords ----------
    for (const f of p.files.filter((x) => /(^|\/)(docker-)?compose[\w.-]*\.ya?ml$/.test(x.path)).map((x) => x.path)) {
      const c = p.read(f) || '';
      const edits = [];
      let m;
      const port = /^(\s*-\s*)(["']?)(5432|3306|27017|6379|9200|5984|1433|26257):(\d+)\2\s*$/gm;
      while ((m = port.exec(c))) {
        seen = true;
        const fd = ctx.at(f, m.index, { category: 'database', severity: 'medium', title: `Database port ${m[3]} published on all network interfaces`, why: 'On a server this exposes the database to the internet, where bots try default passwords constantly.', fix: 'Bind to localhost: "127.0.0.1:PORT:PORT" (or remove the port mapping).' });
        edits.push({ index: m.index, old: m[0], new: `${m[1]}"127.0.0.1:${m[3]}:${m[4]}"`, finding: fd, summary: 'Port now bound to 127.0.0.1 only.' });
      }
      const pw = /(POSTGRES_PASSWORD|MYSQL_ROOT_PASSWORD|MYSQL_PASSWORD|MONGO_INITDB_ROOT_PASSWORD|REDIS_PASSWORD)\s*[:=]\s*["']?(postgres|password|root|admin|example|secret|123456|changeme|mongo)["']?\s*$/gim;
      while ((m = pw.exec(c))) {
        seen = true;
        ctx.at(f, m.index, { category: 'database', severity: 'high', title: `Default database password for ${m[1]}`, why: 'Default credentials are the first thing attackers try.', fix: `Use \${${m[1]}} and set a long random value in .env.` });
      }
      ctx.applyEdits(f, edits);
    }

    // ---------- connection TLS & misc ----------
    for (const f of p.codeFiles((x) => /\.(m|c)?(js|ts)$|\.py$|\.env/.test(x)).map((x) => x.path)) {
      const c = p.read(f) || '';
      let m = /rejectUnauthorized\s*:\s*false/.exec(c);
      if (m) { seen = true; ctx.at(f, m.index, { category: 'https', severity: 'medium', title: 'TLS certificate checking disabled (rejectUnauthorized: false)', why: 'Connections can be intercepted by anyone on the network path (man-in-the-middle).', fix: "Use the provider's CA certificate (ssl: { ca: ... }) instead of disabling verification." }); }
      m = /sslmode=disable|ssl\s*[:=]\s*false/i.exec(c);
      if (m && /postgres|mysql|database|db/i.test(c)) { seen = true; ctx.at(f, m.index, { category: 'database', severity: 'low', title: 'Database connection without TLS', why: 'Credentials and data travel unencrypted if the database is not on the same machine.', fix: 'Use sslmode=require (Postgres) / ssl: true for remote databases.' }); }
      m = /NODE_TLS_REJECT_UNAUTHORIZED\s*=\s*['"]?0/.exec(c);
      if (m) ctx.at(f, m.index, { category: 'https', severity: 'high', title: 'NODE_TLS_REJECT_UNAUTHORIZED=0', why: 'Disables HTTPS certificate checks for the entire Node process.', fix: 'Remove it and fix the certificate problem properly.' });
    }
    if (seen) ctx.checked('database');
    else ctx.na('database', 'No database usage detected.');
  },
};
