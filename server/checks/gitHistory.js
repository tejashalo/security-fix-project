'use strict';
const git = require('../lib/git');
const { findSecrets } = require('../lib/patterns');
const { isPlaceholder, shannon, redact } = require('../lib/util');

const SENSITIVE_FILE_RE = /(^|\/)(\.env(\.(?!example|sample|template)[\w-]+)?|id_rsa|id_ed25519|.*\.pem|.*\.p12|.*\.pfx|.*\.jks|.*\.keystore|service-account.*\.json|.*firebase-adminsdk.*\.json|credentials\.json|.*\.sqlite3?|.*\.sql|sftp\.json)$/i;

module.exports = {
  id: 'git',
  title: 'Searching git history for leaked secrets',
  async run(ctx) {
    const { p } = ctx;
    if (!p.hasGit) {
      ctx.na('git', 'No .git folder in the upload. To scan history, zip the project including the hidden .git folder, or scan a GitHub URL.');
      return;
    }
    ctx.checked('git');
    const commits = git.commitCount(p.root);
    ctx.gitInfo = { commits };

    // 1. secrets added in any commit
    const lines = git.historyAddedLines(p.root);
    const seen = new Map(); // value -> record
    for (const l of lines) {
      if (/(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml)$/.test(l.file)) continue;
      const isExample = /\.(example|sample|template)$/.test(l.file);
      for (const h of findSecrets(l.text, { generic: !/\.(md|txt)$/.test(l.file), isPlaceholder, shannon })) {
        if (h.pattern.supabaseAnon) continue;
        if (isExample && h.pattern.id === 'generic') continue;
        if (!seen.has(h.value)) seen.set(h.value, { ...h, commit: l.commit, file: l.file, count: 0 });
        seen.get(h.value).count++;
      }
    }
    const currentContent = p.codeFiles().map((f) => p.read(f.path) || '').join('\n');
    for (const rec of seen.values()) {
      ctx.secretValues.add(rec.value);
      const stillInCode = currentContent.includes(rec.value);
      ctx.add({
        category: 'git', severity: rec.pattern.severity === 'critical' || rec.pattern.serviceRole ? 'critical' : 'high',
        file: rec.file, line: null,
        snippet: `commit ${rec.commit.hash.slice(0, 8)} (${rec.commit.date}) — "${rec.commit.message.slice(0, 60)}" — ${rec.pattern.name}: ${redact(rec.value)}`,
        title: `${rec.pattern.name} found in git history${stillInCode ? '' : ' (deleted from code, still in history)'}`,
        why: 'Deleting a secret from your code does not remove it from git. Anyone who can clone the repo can check out the old commit and copy it.',
        fix: 'Rotate this key first (most important). Then rewrite history with git-filter-repo using the replacements file VibeGuard generated (.vibeguard/git-filter-repo-replacements.txt) and force-push.',
      });
    }

    // 2. sensitive files ever committed
    const ever = git.everCommittedFiles(p.root).filter((f) => SENSITIVE_FILE_RE.test(f) && !/(^|\/)(migrations?|schema|seeds?|init|supabase|prisma|db\/migrate)[\w./-]*\.sql$/i.test(f));
    for (const f of ever) {
      ctx.add({
        category: 'git', severity: /\.env|pem|key|keystore|jks|p12|service-account|adminsdk|credentials|id_rsa|id_ed/i.test(f) ? 'critical' : 'high',
        file: f, title: `Sensitive file "${f}" was committed at some point`,
        why: 'Files that were ever committed stay readable in history, even after being deleted.',
        fix: `Remove it from history: \`git filter-repo --invert-paths --path ${f}\` then force-push. Rotate anything it contained.`,
      });
    }

    // 3. Generate a replacements file for git-filter-repo (kept out of git)
    if (seen.size) {
      const body = '# Generated by VibeGuard. Use with: git filter-repo --replace-text .vibeguard/git-filter-repo-replacements.txt\n'
        + '# This file contains real secrets — do NOT commit it. Delete it after cleaning history.\n'
        + [...seen.keys()].map((v) => `${v}==>REMOVED_BY_VIBEGUARD`).join('\n') + '\n';
      ctx.p.write('.vibeguard/git-filter-repo-replacements.txt', body);
      ctx.generated.push({ file: '.vibeguard/git-filter-repo-replacements.txt', why: 'Ready-made input for `git filter-repo --replace-text` to scrub leaked secrets from history (git-ignored).' });
      ctx.ensureGitignore(['.vibeguard/']);
      ctx.note('To scrub leaked secrets from git history: `pip install git-filter-repo`, then from your repo run `git filter-repo --replace-text .vibeguard/git-filter-repo-replacements.txt`, then `git push --force --all`. Everyone else must re-clone. Rotate the keys anyway.');
    }
  },
};
