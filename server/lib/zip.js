'use strict';
/**
 * Minimal, dependency-free ZIP reader/writer with defensive limits.
 * Protects against: zip-slip (path traversal), zip bombs, symlink entries,
 * encrypted entries, and oversized archives.
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

class ZipError extends Error {
  constructor(message) { super(message); this.name = 'ZipError'; this.userFacing = true; }
}

// ---------- CRC32 ----------
let CRC_TABLE = null;
function crc32(buf) {
  if (typeof zlib.crc32 === 'function') return zlib.crc32(buf) >>> 0;
  if (!CRC_TABLE) {
    CRC_TABLE = new Uint32Array(256);
    for (let n = 0; n < 256; n++) {
      let c = n;
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
      CRC_TABLE[n] = c >>> 0;
    }
  }
  let crc = 0xffffffff;
  for (let i = 0; i < buf.length; i++) crc = CRC_TABLE[(crc ^ buf[i]) & 0xff] ^ (crc >>> 8);
  return (crc ^ 0xffffffff) >>> 0;
}

// ---------- Reader ----------
function findEOCD(buf) {
  const min = Math.max(0, buf.length - 65557);
  for (let i = buf.length - 22; i >= min; i--) {
    if (buf.readUInt32LE(i) === 0x06054b50) return i;
  }
  throw new ZipError('This file is not a valid ZIP archive.');
}

function listEntries(buf) {
  const eocd = findEOCD(buf);
  const count = buf.readUInt16LE(eocd + 10);
  const cdSize = buf.readUInt32LE(eocd + 12);
  const cdOffset = buf.readUInt32LE(eocd + 16);
  if (count === 0xffff || cdOffset === 0xffffffff) throw new ZipError('ZIP64 archives are not supported. Please create a standard ZIP.');
  if (cdOffset + cdSize > buf.length) throw new ZipError('Corrupted ZIP archive (central directory out of range).');
  const entries = [];
  let p = cdOffset;
  for (let i = 0; i < count; i++) {
    if (p + 46 > buf.length || buf.readUInt32LE(p) !== 0x02014b50) throw new ZipError('Corrupted ZIP archive (bad central directory).');
    const madeBy = buf.readUInt16LE(p + 4);
    const flags = buf.readUInt16LE(p + 8);
    const method = buf.readUInt16LE(p + 10);
    const compSize = buf.readUInt32LE(p + 20);
    const size = buf.readUInt32LE(p + 24);
    const nameLen = buf.readUInt16LE(p + 28);
    const extraLen = buf.readUInt16LE(p + 30);
    const commentLen = buf.readUInt16LE(p + 32);
    const extAttr = buf.readUInt32LE(p + 38);
    const localOffset = buf.readUInt32LE(p + 42);
    const name = buf.slice(p + 46, p + 46 + nameLen).toString('utf8').replace(/\\/g, '/');
    const unixMode = (madeBy >> 8) === 3 ? (extAttr >>> 16) : 0;
    entries.push({
      name, method, flags, compSize, size, localOffset,
      isDirectory: name.endsWith('/'),
      isSymlink: (unixMode & 0o170000) === 0o120000,
      encrypted: (flags & 1) === 1,
    });
    p += 46 + nameLen + extraLen + commentLen;
  }
  return entries;
}

function readEntryData(buf, e, maxBytes) {
  const lo = e.localOffset;
  if (lo + 30 > buf.length || buf.readUInt32LE(lo) !== 0x04034b50) throw new ZipError('Corrupted ZIP archive (bad local header).');
  const nameLen = buf.readUInt16LE(lo + 26);
  const extraLen = buf.readUInt16LE(lo + 28);
  const start = lo + 30 + nameLen + extraLen;
  const end = start + e.compSize;
  if (end > buf.length) throw new ZipError('Corrupted ZIP archive (entry out of range).');
  const raw = buf.subarray(start, end);
  if (e.method === 0) {
    if (raw.length > maxBytes) throw new ZipError(`File "${e.name}" is too large.`);
    return Buffer.from(raw);
  }
  if (e.method === 8) {
    try {
      return zlib.inflateRawSync(raw, { maxOutputLength: Math.max(1, maxBytes) });
    } catch (err) {
      if (err && (err.code === 'ERR_BUFFER_TOO_LARGE' || err instanceof RangeError)) {
        throw new ZipError(`File "${e.name}" expands beyond the size limit (possible zip bomb).`);
      }
      throw new ZipError(`Could not decompress "${e.name}".`);
    }
  }
  throw new ZipError(`Unsupported compression method in "${e.name}". Please re-create the ZIP with standard settings.`);
}

const DEFAULT_LIMITS = {
  maxEntries: 20000,
  maxTotalBytes: 300 * 1024 * 1024,
  maxFileBytes: 25 * 1024 * 1024,
};

// Folders we never extract: they are regenerated by package managers and huge.
const SKIP_EXTRACT = /(^|\/)(node_modules|__MACOSX|\.venv|venv|Pods|\.gradle|\.dart_tool|\.next\/cache)(\/|$)/;

/**
 * Safely extracts a ZIP buffer into `dest` (which must exist and be empty).
 * Returns { root, stats } where root is the project root (unwraps a single top folder).
 */
function safeExtract(buf, dest, limits = {}) {
  const L = { ...DEFAULT_LIMITS, ...limits };
  const entries = listEntries(buf);
  if (entries.length > L.maxEntries) throw new ZipError(`ZIP has ${entries.length} entries; the limit is ${L.maxEntries}. Remove node_modules/build folders and try again.`);
  const destAbs = path.resolve(dest);
  const stats = { files: 0, skippedDeps: 0, skippedSymlinks: 0, skippedLarge: 0, skippedEncrypted: 0, totalBytes: 0 };
  for (const e of entries) {
    if (e.isDirectory) continue;
    if (SKIP_EXTRACT.test(e.name)) { stats.skippedDeps++; continue; }
    if (e.isSymlink) { stats.skippedSymlinks++; continue; }
    if (e.encrypted) { stats.skippedEncrypted++; continue; }
    if (!e.name || e.name.includes('\0')) throw new ZipError('ZIP contains an invalid file name.');
    const target = path.resolve(destAbs, e.name);
    if (!target.startsWith(destAbs + path.sep)) throw new ZipError(`Blocked unsafe path in ZIP: "${e.name}" (zip-slip attempt).`);
    if (e.size > L.maxFileBytes) { stats.skippedLarge++; continue; }
    if (stats.totalBytes + e.size > L.maxTotalBytes) throw new ZipError('ZIP expands to more than the allowed total size.');
    const data = readEntryData(buf, e, Math.min(L.maxFileBytes, L.maxTotalBytes - stats.totalBytes) + 1);
    if (data.length > L.maxFileBytes) { stats.skippedLarge++; continue; }
    stats.totalBytes += data.length;
    if (stats.totalBytes > L.maxTotalBytes) throw new ZipError('ZIP expands to more than the allowed total size.');
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, data, { mode: 0o644 });
    stats.files++;
  }
  if (stats.files === 0) throw new ZipError('The ZIP did not contain any project files.');
  // Unwrap a single top-level folder (common when zipping a project folder).
  let root = destAbs;
  for (let i = 0; i < 3; i++) {
    const items = fs.readdirSync(root).filter((n) => n !== '__MACOSX' && n !== '.DS_Store');
    if (items.length === 1 && fs.statSync(path.join(root, items[0])).isDirectory() && items[0] !== '.git') {
      root = path.join(root, items[0]);
    } else break;
  }
  return { root, stats };
}

// ---------- Writer ----------
function dosDateTime(d = new Date()) {
  const time = (d.getHours() << 11) | (d.getMinutes() << 5) | Math.floor(d.getSeconds() / 2);
  const date = ((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate();
  return { time, date };
}

/** files: Array<{ name: string, data: Buffer }> → Buffer */
function createZip(files) {
  const { time, date } = dosDateTime();
  const locals = [];
  const centrals = [];
  let offset = 0;
  for (const f of files) {
    const name = Buffer.from(f.name.replace(/\\/g, '/'), 'utf8');
    const data = Buffer.isBuffer(f.data) ? f.data : Buffer.from(f.data);
    const crc = crc32(data);
    let comp = zlib.deflateRawSync(data, { level: 6 });
    let method = 8;
    if (comp.length >= data.length) { comp = data; method = 0; }
    const lh = Buffer.alloc(30);
    lh.writeUInt32LE(0x04034b50, 0);
    lh.writeUInt16LE(20, 4);
    lh.writeUInt16LE(0x0800, 6); // UTF-8 names
    lh.writeUInt16LE(method, 8);
    lh.writeUInt16LE(time, 10);
    lh.writeUInt16LE(date, 12);
    lh.writeUInt32LE(crc, 14);
    lh.writeUInt32LE(comp.length, 18);
    lh.writeUInt32LE(data.length, 22);
    lh.writeUInt16LE(name.length, 26);
    lh.writeUInt16LE(0, 28);
    locals.push(lh, name, comp);
    const ch = Buffer.alloc(46);
    ch.writeUInt32LE(0x02014b50, 0);
    ch.writeUInt16LE(0x031e, 4); // made by: unix, v3.0
    ch.writeUInt16LE(20, 6);
    ch.writeUInt16LE(0x0800, 8);
    ch.writeUInt16LE(method, 10);
    ch.writeUInt16LE(time, 12);
    ch.writeUInt16LE(date, 14);
    ch.writeUInt32LE(crc, 16);
    ch.writeUInt32LE(comp.length, 20);
    ch.writeUInt32LE(data.length, 24);
    ch.writeUInt16LE(name.length, 28);
    ch.writeUInt32LE((0o100644 << 16) >>> 0, 38);
    ch.writeUInt32LE(offset, 42);
    centrals.push(ch, name);
    offset += 30 + name.length + comp.length;
  }
  const cd = Buffer.concat(centrals);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0);
  eocd.writeUInt16LE(files.length, 8);
  eocd.writeUInt16LE(files.length, 10);
  eocd.writeUInt32LE(cd.length, 12);
  eocd.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, cd, eocd]);
}

/** Zips a directory tree, skipping folders matched by `exclude` (relative posix paths). */
function zipDirectory(dir, { exclude = /(^|\/)(\.git|node_modules)(\/|$)/, prefix = '' } = {}) {
  const files = [];
  (function walk(rel) {
    const abs = path.join(dir, rel);
    for (const ent of fs.readdirSync(abs, { withFileTypes: true })) {
      const r = rel ? `${rel}/${ent.name}` : ent.name;
      if (exclude.test(r)) continue;
      if (ent.isSymbolicLink()) continue;
      if (ent.isDirectory()) walk(r);
      else if (ent.isFile()) files.push({ name: prefix + r, data: fs.readFileSync(path.join(dir, r)) });
    }
  })('');
  return createZip(files);
}

module.exports = { safeExtract, createZip, zipDirectory, listEntries, ZipError, crc32 };
